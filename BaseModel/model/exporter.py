"""Exporter utility to bundle all registered model layers into a standalone, single-file Python module."""
import inspect
import os
import re
from typing import List, Optional, Set, Type
import torch.nn as nn

from BaseModel.core.registrar import (
    BACKBONES,
    HEADS,
    LAYERS,
    MODELS,
    NECKS,
)
from BaseModel.model.base_model import BaseModel


def export_model_to_single_file(
    output_path: str,
    target_models: Optional[List[str]] = None,
    include_all_layers: bool = True,
) -> str:
    """Consolidates all registered models, backbones, necks, heads, and layers into a single self-contained Python file.

    It automatically:
    1. Extracts source code of BaseModel and all registered components.
    2. Strips local registry decorators (@MODELS.register_module(), etc.) so the file runs anywhere without BaseModel dependencies.
    3. Bundles standard Python & PyTorch imports needed to execute the model.

    Args:
        output_path: File path to save the consolidated Python script (e.g. 'exported_model.py').
        target_models: Specific list of model names to include (if None, includes all registered models).
        include_all_layers: Whether to bundle all registered layers/backbones/necks/heads.

    Returns:
        The absolute path to the generated single file.
    """
    output_dir = os.path.dirname(os.path.abspath(output_path))
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    # 1. Collect all target classes
    ordered_classes: List[Type] = []
    seen_classes: Set[Type] = set()

    def add_class(cls: Type):
        if not inspect.isclass(cls):
            return
        if cls in seen_classes or cls is nn.Module:
            return
        seen_classes.add(cls)
        ordered_classes.append(cls)

    # Always add BaseModel first
    add_class(BaseModel)

    # Collect registered components in dependency order: Layers -> Backbones -> Necks -> Heads -> Models
    registries_in_order = [LAYERS, BACKBONES, NECKS, HEADS]
    if include_all_layers:
        for reg in registries_in_order:
            for name, cls in reg.module_dict.items():
                add_class(cls)

    for name, cls in MODELS.module_dict.items():
        if target_models is None or name in target_models:
            add_class(cls)

    # 2. Prepare header imports (Standard libraries + PyTorch)
    header = '''"""Autogenerated Standalone Model File.
Bundles all model components, submodules, layers, and dependencies into a single file.
Can be imported and executed independently without BaseModel framework dependencies.
"""
from abc import ABC, abstractmethod
import math
import os
import random
from typing import Any, Callable, Dict, List, Optional, Sequence, Tuple, Union

import torch
import torch.nn as nn
import torch.nn.functional as F

'''

    # Pattern to remove registry decorators: e.g. @MODELS.register_module(...) or @LAYERS.register_module()
    decorator_pattern = re.compile(r"^@(?:MODELS|BACKBONES|NECKS|HEADS|LAYERS)\.register_module\(.*?\)\s*\n", re.MULTILINE)

    sections: List[str] = [header]

    for cls in ordered_classes:
        try:
            source = inspect.getsource(cls)
            # Remove decorator lines
            cleaned_source = decorator_pattern.sub("", source)
            sections.append(f"# {'=' * 70}\n# {cls.__name__}\n# {'=' * 70}\n{cleaned_source.strip()}\n\n")
        except Exception as e:
            print(f"[Warning] Could not extract source code for {cls.__name__}: {e}")

    final_content = "\n".join(sections)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(final_content)

    return os.path.abspath(output_path)
